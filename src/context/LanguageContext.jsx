const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    return localStorage.getItem("mixhub_language") || "en";
  });

  useEffect(() => {
    localStorage.setItem("mixhub_language", currentLang);
    const langObj = LANGUAGES.find((l) => l.code === currentLang);
    if (langObj?.dir === "rtl") {
      document.documentElement.setAttribute("dir", "rtl");
    } else {
      document.documentElement.setAttribute("dir", "ltr");
    }
  }, [currentLang]);

  const t = (key) => {
    const langSet = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    return langSet[key] || TRANSLATIONS.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLang, setCurrentLang, t, LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

